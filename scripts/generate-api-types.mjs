#!/usr/bin/env node
/**
 * Generates app/lib/api/schema.d.ts from the backend's OpenAPI document.
 *
 * Source (first match wins):
 *   1. CLI argument:        pnpm api:types -- http://localhost:3100/api/v1/openapi.json
 *   2. ATRIUM_OPENAPI env:  file path or http(s) URL
 *   3. Default:             ../atrium-backend-demo/openapi.json
 *
 * scripts/openapi.placeholder.json is the stand-in used until the backend publishes its document:
 *   pnpm api:types -- scripts/openapi.placeholder.json
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const output = resolve(root, 'app/lib/api/schema.d.ts')
const source =
  process.argv.slice(2).find((arg) => arg !== '--') ??
  process.env.ATRIUM_OPENAPI ??
  '../atrium-backend-demo/openapi.json'

let input
let label
if (/^https?:\/\//i.test(source)) {
  input = new URL(source)
  label = source
} else {
  const file = resolve(root, source)
  if (!existsSync(file)) {
    console.error(
      `[api:types] OpenAPI document not found: ${file}\n` +
        '  Pass a path/URL (pnpm api:types -- <path-or-url>) or set ATRIUM_OPENAPI.',
    )
    process.exit(1)
  }
  input = pathToFileURL(file)
  label = relative(root, file).replaceAll('\\', '/')
}

const ast = await openapiTS(input, { alphabetize: true })
const header = [
  '/**',
  ' * This file was auto-generated by openapi-typescript (pnpm api:types).',
  ` * Source: ${label}`,
  ' * Do not make direct changes to the file.',
  ' */',
  '',
  '',
].join('\n')

mkdirSync(dirname(output), { recursive: true })
writeFileSync(output, header + astToString(ast))
console.log(`[api:types] wrote ${relative(root, output).replaceAll('\\', '/')} from ${label}`)
