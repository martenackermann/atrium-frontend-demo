#!/usr/bin/env node
/**
 * Generates app/lib/api/schema.d.ts from the backend's OpenAPI document.
 *
 * Source (first match wins):
 *   1. CLI argument:        pnpm api:types -- http://localhost:3100/api/openapi.json
 *   2. ATRIUM_OPENAPI env:  file path or http(s) URL
 *   3. Default:             ../atrium-backend-demo/openapi.json
 *
 * The backend documents full paths (`/api/v1/health`); the client's base URL already ends in
 * `/api/v1`, so that prefix is stripped from every path key (override with ATRIUM_OPENAPI_PREFIX,
 * empty to disable).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const output = resolve(root, 'app/lib/api/schema.d.ts')
const source =
  process.argv.slice(2).find((arg) => arg !== '--') ??
  process.env.ATRIUM_OPENAPI ??
  '../atrium-backend-demo/openapi.json'
const prefix = process.env.ATRIUM_OPENAPI_PREFIX ?? '/api/v1'

let document
let label
if (/^https?:\/\//i.test(source)) {
  const response = await fetch(source)
  if (!response.ok) {
    console.error(`[api:types] ${source} answered ${response.status}`)
    process.exit(1)
  }
  document = await response.json()
  label = source
} else {
  const file = resolve(root, source)
  if (!existsSync(file)) {
    console.error(
      `[api:types] OpenAPI document not found: ${file}\n` +
        '  Pass a path/URL (pnpm api:types -- <path-or-url>) or set ATRIUM_OPENAPI.',
    )
    process.exit(1)
  }
  document = JSON.parse(readFileSync(file, 'utf8'))
  label = relative(root, file).replaceAll('\\', '/')
}

if (prefix && document.paths) {
  document.paths = Object.fromEntries(
    Object.entries(document.paths).map(([path, item]) => [
      path.startsWith(`${prefix}/`) ? path.slice(prefix.length) : path,
      item,
    ]),
  )
}

const ast = await openapiTS(document, { alphabetize: true })
const header = [
  '/**',
  ' * This file was auto-generated by openapi-typescript (pnpm api:types).',
  ` * Source: ${label}${prefix ? ` (path prefix "${prefix}" stripped)` : ''}`,
  ' * Do not make direct changes to the file.',
  ' */',
  '',
  '',
].join('\n')

mkdirSync(dirname(output), { recursive: true })
writeFileSync(output, header + astToString(ast))
console.log(`[api:types] wrote ${relative(root, output).replaceAll('\\', '/')} from ${label}`)
